// Бесконечный спуск: за десятым этажом таблицы кончаются, и этаж
// собирается из того, что есть, — по кругу. Среду прокручиваем только
// по настоящим средам: null-ы первых четырёх этажей в круг не входят.
const HAZARD_CYCLE = FLOOR_HAZARD.filter(Boolean);

function cycleAt(list, index) {
  if (!list || !list.length) return null;
  return list[index % list.length] || null;
}

function floorHazard(index) {
  const key =
    index >= 0 && index < FLOOR_HAZARD.length
      ? FLOOR_HAZARD[index]
      : cycleAt(HAZARD_CYCLE, index - FLOOR_HAZARD.length);
  return key ? HAZARD_TYPES[key] || null : null;
}

function hazardDensity(key) {
  return HAZARD_DENSITY[key] || 0;
}

// Выбор показывается только с BLESS.from и только один раз на этаж.
function blessOffered(index, chosen) {
  if (index < BLESS.from) return false;
  return !chosen || !BLESSINGS[chosen];
}

// Уже выбранная сделка. Раньше здесь стояла проверка blessOffered, и она
// отсекала ровно тот случай, ради которого функция нужна: выбранную сделку.
// Из-за этого цена «Каменного дара» (регенерация врагов) не работала вовсе.
function blessingFor(index, chosen) {
  if (index < BLESS.from) return null;
  return BLESSINGS[chosen] || null;
}

